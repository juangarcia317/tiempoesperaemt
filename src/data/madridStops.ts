export function findStopInCatalog(stopId: string): MadridStopCatalogItem | undefined {
  const cleanId = stopId.trim();
  return MADRID_POPULAR_STOPS.find(s => s.stopId === cleanId);
}

export function searchCatalog(query: string): MadridStopCatalogItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  
  return MADRID_POPULAR_STOPS.filter(s => {
    return (
      s.stopId.includes(q) ||
      s.name.toLowerCase().includes(q) ||
      s.address.toLowerCase().includes(q) ||
      s.zone?.toLowerCase().includes(q) ||
      s.lines.some(l => l.toLowerCase() === q || l.toLowerCase().includes(q))
    );
  }).slice(0, 8);
}

export function getLineBadgeTheme(lineNumber: string): {
  bg: string;
  text: string;
  border?: string;
  badgeType: string;
} {
  const line = lineNumber.toUpperCase().trim();
  
  // Líneas Cero emisiones (001, 002)
  if (line.startsWith('00') || line === 'C03') {
    return {
      bg: 'bg-emerald-600',
      text: 'text-white',
      badgeType: 'Cero Emisiones',
    };
  }

  // Circular C1, C2
  if (line === 'C1' || line === 'C2') {
    return {
      bg: 'bg-amber-600',
      text: 'text-white',
      badgeType: 'Circular',
    };
  }

  // Exprés Aeropuerto 203
  if (line === '203') {
    return {
      bg: 'bg-yellow-400',
      text: 'text-zinc-950 font-black',
      border: 'border border-yellow-500',
      badgeType: 'Exprés Aeropuerto',
    };
  }

  // Nocturnos Búhos N1-N28, NC1, NC2
  if (line.startsWith('N')) {
    return {
      bg: 'bg-slate-900',
      text: 'text-cyan-400 font-bold',
      border: 'border border-cyan-700/50',
      badgeType: 'Nocturno (Búho)',
    };
  }

  // Universitarias (A, F, G, U)
  if (['A', 'E', 'F', 'G', 'U', 'H'].includes(line)) {
    return {
      bg: 'bg-purple-700',
      text: 'text-white',
      badgeType: 'Universitaria / Especial',
    };
  }

  // Líneas Exprés (E1, E2, E3, E4, E5, E6)
  if (line.startsWith('E')) {
    return {
      bg: 'bg-rose-700',
      text: 'text-white',
      badgeType: 'Línea Exprés',
    };
  }

  // Líneas convencionales de la EMT (Azul corporativo EMT Madrid)
  return {
    bg: 'bg-[#005696]',
    text: 'text-white',
    badgeType: 'EMT Convencional',
  };
}

export function formatArrivalTime(seconds: number): {
  displayText: string;
  minutes: number;
  urgency: 'imminent' | 'soon' | 'moderate' | 'distant' | 'unknown';
  subText?: string;
} {
  if (seconds === undefined || seconds === null || isNaN(seconds)) {
    return {
      displayText: 'Consultando...',
      minutes: 0,
      urgency: 'unknown',
    };
  }

  // En la API de EMT, valores >= 999999 o > 3600 segundos suelen indicar más de 20-30 min
  if (seconds >= 999999) {
    return {
      displayText: '> 20 min',
      minutes: 20,
      urgency: 'distant',
      subText: 'Frecuencia programada',
    };
  }

  if (seconds <= 45) {
    return {
      displayText: 'LLEGANDO',
      minutes: 0,
      urgency: 'imminent',
      subText: 'En parada o aproximándose',
    };
  }

  const minutes = Math.round(seconds / 60);

  if (minutes <= 1) {
    return {
      displayText: '< 1 min',
      minutes: 1,
      urgency: 'imminent',
      subText: `${seconds} seg restantes`,
    };
  }

  if (minutes <= 4) {
    return {
      displayText: `${minutes} min`,
      minutes,
      urgency: 'soon',
      subText: `${Math.floor(seconds / 60)}m ${seconds % 60}s`,
    };
  }

  if (minutes <= 12) {
    return {
      displayText: `${minutes} min`,
      minutes,
      urgency: 'moderate',
      subText: `Aprox. ${minutes} minutos`,
    };
  }

  return {
    displayText: `${minutes} min`,
    minutes,
    urgency: 'distant',
    subText: `Aprox. ${minutes} minutos`,
  };
}
